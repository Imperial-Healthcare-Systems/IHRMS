// Reads the workflow output JSON and produces AUDIT.md grouped by severity.
import { readFileSync, writeFileSync } from 'node:fs'

const inputPath = process.argv[2]
const outputPath = process.argv[3] ?? 'AUDIT.md'

if (!inputPath) {
  console.error('Usage: node scripts/format-audit-report.mjs <input-json-path> [output-md-path]')
  process.exit(1)
}

const raw = readFileSync(inputPath, 'utf8')
const envelope = JSON.parse(raw)
const data = envelope.result ?? envelope

const sevOrder = { critical: 0, high: 1, medium: 2, low: 3 }
const findings = (data.confirmedFindings ?? []).slice().sort((a, b) => {
  const sa = sevOrder[a.severity] ?? 99
  const sb = sevOrder[b.severity] ?? 99
  if (sa !== sb) return sa - sb
  return (a.dimension ?? '').localeCompare(b.dimension ?? '')
})

const groups = { critical: [], high: [], medium: [], low: [] }
for (const f of findings) {
  ;(groups[f.severity] ?? groups.low).push(f)
}

const dimensionLabels = {
  'auth-rls':         'Auth + RLS boundary',
  'schema-drift':     'Schema-code drift',
  'route-correctness':'Route correctness',
  'business-logic':   'Business logic',
  'perf-scalability': 'Performance',
  'observability':    'Observability',
}

const lines = []
lines.push('# IHRMS Audit')
lines.push('')
lines.push(`Auto-generated by the multi-agent audit workflow.`)
lines.push('')
lines.push(`**Confirmed findings:** ${findings.length}`)
lines.push(`(Verified by 3 adversarial reviewers per finding; majority-real required to survive.)`)
lines.push('')
lines.push('## Summary by dimension')
lines.push('')
lines.push('| Dimension | Surveyed | Confirmed | Rejected |')
lines.push('|---|---:|---:|---:|')
for (const d of data.byDimension ?? []) {
  lines.push(`| ${dimensionLabels[d.dimension] ?? d.dimension} | ${d.totalFindings} | ${d.confirmed} | ${d.rejected} |`)
}
lines.push('')
lines.push('## Summary by severity')
lines.push('')
lines.push(`- **Critical:** ${groups.critical.length}`)
lines.push(`- **High:** ${groups.high.length}`)
lines.push(`- **Medium:** ${groups.medium.length}`)
lines.push(`- **Low:** ${groups.low.length}`)
lines.push('')

function renderFinding(f, idx) {
  const lineRef = f.line ? `:${f.line}` : ''
  const fileRef = `\`${(f.file ?? '').replace(/^\//, '')}${lineRef}\``
  const lines = []
  lines.push(`### ${idx}. ${f.title}`)
  lines.push('')
  lines.push(`- **File:** ${fileRef}`)
  lines.push(`- **Severity:** ${f.severity}`)
  lines.push(`- **Dimension:** ${dimensionLabels[f.dimension] ?? f.dimension}`)
  if (f.category) lines.push(`- **Category:** ${f.category}`)
  lines.push('')
  if (f.description) {
    lines.push("**What's wrong**")
    lines.push('')
    lines.push(f.description)
    lines.push('')
  }
  if (f.evidence) {
    lines.push('**Evidence**')
    lines.push('')
    lines.push('```')
    lines.push(String(f.evidence).slice(0, 800))
    lines.push('```')
    lines.push('')
  }
  if (f.impact) {
    lines.push('**Impact**')
    lines.push('')
    lines.push(f.impact)
    lines.push('')
  }
  if (f.fix_sketch) {
    lines.push('**Suggested fix**')
    lines.push('')
    lines.push(f.fix_sketch)
    lines.push('')
  }
  // Verdict consensus line
  if (Array.isArray(f.verdicts) && f.verdicts.length) {
    const real = f.verdicts.filter(v => v.isReal).length
    const conf = f.verdicts.filter(v => v.isReal).map(v => v.confidence)
    lines.push(`<sub>Verifier consensus: ${real}/${f.verdicts.length} real, confidence ${[...new Set(conf)].join('/') || '—'}</sub>`)
    lines.push('')
  }
  return lines.join('\n')
}

let counter = 0
for (const sev of ['critical', 'high', 'medium', 'low']) {
  const group = groups[sev]
  if (group.length === 0) continue
  lines.push('---')
  lines.push('')
  lines.push(`## ${sev[0].toUpperCase() + sev.slice(1)} (${group.length})`)
  lines.push('')
  for (const f of group) {
    counter++
    lines.push(renderFinding(f, counter))
  }
}

writeFileSync(outputPath, lines.join('\n'), 'utf8')
console.log(`Wrote ${outputPath} (${findings.length} findings)`)
console.log(`  critical: ${groups.critical.length}`)
console.log(`  high:     ${groups.high.length}`)
console.log(`  medium:   ${groups.medium.length}`)
console.log(`  low:      ${groups.low.length}`)
